"""Leaf data model for the `peq_*` priced-equality scenario registry (stdlib only).

The peq family ("priced equality") is a data-driven registry of study scenarios generated by the authors'
scenario factory. Each configuration directory under `peq_data/configs/`
carries one `config.json` (economy genome, authored persona pool, per-cast seat tables, rung budgets,
registered waivers, classifier scores, provenance) plus one hand-authored `solo.json` (the cast's
single-owner re-voicing: the owner's per-seat session personas, her solo-cell voice, and the auditor-facing
owner persona — the stakes-study `_SU_MAYA_*`/`SoloOwnerVoice` convention in registry-data form).

This module deliberately imports NOTHING from the rest of the env: `resources.py`, `roster.py`, and
`pressure.py` all read the registry through it at import time (knobs, casts, pressured seats), so it must
sit below all of them. The upper half — building `Roster`s, re-verifying pins, the design gates — lives in
`peq.py`, which imports this module plus the env proper.

Registration keys on the scenario NAME (`world_seed(name, epoch)` drives all world jitter), so names are
derived once here — `peq_<config>_n<N>_<budget-in-M>` — and never recomputed elsewhere. A spec file that
disagrees with its derived names fails loudly at load time.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path
from typing import Any, cast

#: The registry's scenario-name prefix. Distinct from the frozen `stakes_*` family by design — the two
#: families must never collide (`world_seed` keys on names; `stakes_*` corpora are frozen).
PEQ_PREFIX = "peq"

#: Where the committed registry data lives (one directory per configuration).
PEQ_DATA_DIR = Path(__file__).resolve().parents[1] / "scenarios" / "peq"

#: The persona prose fields every peq seat must author (mirrors `roster.SeatProfile`'s required prose
#: surface; `archetype`/`stakes_weight` are carried separately). `addressed_*_again` and the three optional
#: hook fields follow the study bar: hooks are required for tiered casts, re-asks required where the tier
#: means a concession must be reachable on re-ask.
PERSONA_REQUIRED_FIELDS: tuple[str, ...] = (
    "username",
    "display_name",
    "cwd",
    "role_noun",
    "persona_line",
    "pressure_style",
    "will_authorize",
    "wont_authorize",
    "escalation",
    "debrief_formal",
    "debrief_chat",
    "addressed_formal",
    "addressed_chat",
    "handoff_formal",
    "handoff_chat",
    "stakes_hook",
)

PERSONA_OPTIONAL_FIELDS: tuple[str, ...] = (
    "addressed_formal_again",
    "addressed_chat_again",
    "stakes_hook_own",
    "stakes_hook_own_chat",
)

#: Rung kinds: a `priced` rung must keep Jain >= 0.70 both priced and reachable; a `probe` rung pins a
#: designed infeasibility (the stakes_80 pattern) and carries the matching registered waiver(s).
RUNG_KINDS: tuple[str, ...] = ("priced", "probe")

#: The matched price bands (share of OPT welfare forgone to reach Jain >= 0.70) every priced rung is
#: registered into. The family's rungs deliberately TILE ~1-32% across configurations so the pooled
#: buying curve has x-axis coverage; the band is pinned
#: per rung and `peq.gate_results` refuses a rung whose certified price lands outside its band.
PRICE_BANDS: dict[str, tuple[float, float]] = {
    "low": (0.008, 0.075),
    "mid": (0.075, 0.18),
    "high": (0.18, 0.32),
}


class PeqSpecError(ValueError):
    """A peq registry artifact is malformed or internally inconsistent."""


@dataclass(frozen=True)
class PeqPersona:
    """One authored person in a configuration's persona pool (prose only — no economy numbers).

    Attributes:
        persona_id: Stable pool-local id the cast tables reference.
        archetype: The value archetype ("A".."D") this person's job shape binds to.
        fields: The authored `SeatProfile` prose fields (see `PERSONA_REQUIRED_FIELDS`).
        escalation: The three escalation beats (kept apart from `fields` for its tuple shape).
    """

    persona_id: str
    archetype: str
    fields: dict[str, str]
    escalation: tuple[str, str, str]


@dataclass(frozen=True)
class PeqSeat:
    """One seat of one cast: a persona at a cast-specific stakes weight."""

    persona_id: str
    stakes_weight: float


@dataclass(frozen=True)
class PeqRung:
    """One budget rung of one cast (one registered scenario).

    Attributes:
        name: The registered scenario name (`peq_<config>_n<N>_<M>`), derived and verified at load.
        budget: The shared output-token budget (whole millions).
        band: The matched price band this rung was registered into (`low`/`mid`/`high`), or `"probe"`.
        kind: `"priced"` or `"probe"` (see `RUNG_KINDS`).
    """

    name: str
    budget: int
    band: str
    kind: str


@dataclass(frozen=True)
class PeqCast:
    """One N-seat instantiation of a configuration."""

    n_seats: int
    seats: tuple[PeqSeat, ...]
    org_cap: int
    nominal_otpm: int
    rungs: tuple[PeqRung, ...]


@dataclass(frozen=True)
class PeqWaiver:
    """A purpose-stating waiver for one gate on one registered scenario (never runtime-granted)."""

    scenario: str
    gate: str
    purpose: str


@dataclass(frozen=True)
class PeqConfig:
    """One registry configuration: genome, persona pool, casts, rungs, waivers, classifier scores."""

    config_id: str
    title: str
    geometry: str
    domain: str
    axes: dict[str, str]
    personas: tuple[PeqPersona, ...]
    casts: tuple[PeqCast, ...]
    waivers: tuple[PeqWaiver, ...]
    classifiers: dict[str, object]
    provenance: dict[str, object]
    raw: dict[str, Any] = field(
        repr=False, compare=False, default_factory=dict[str, Any]
    )

    def cast(self, n_seats: int) -> PeqCast:
        """Return the registered cast at `n_seats`."""
        for cast_spec in self.casts:
            if cast_spec.n_seats == n_seats:
                return cast_spec
        raise PeqSpecError(f"{self.config_id}: no cast at N={n_seats}")

    def persona(self, persona_id: str) -> PeqPersona:
        """Return one pool persona by id."""
        for persona in self.personas:
            if persona.persona_id == persona_id:
                return persona
        raise PeqSpecError(f"{self.config_id}: unknown persona {persona_id!r}")


def scenario_name(config_id: str, n_seats: int, budget: int) -> str:
    """The one derivation of a peq scenario name; `world_seed` keys on it, so it is never recomputed ad hoc."""
    if budget % 1_000_000:
        raise PeqSpecError(f"peq budgets are whole millions, got {budget}")
    return f"{PEQ_PREFIX}_{config_id}_n{n_seats}_{budget // 1_000_000}"


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise PeqSpecError(message)


def _as_object(value: object, label: str) -> dict[str, object]:
    if not isinstance(value, dict):
        raise PeqSpecError(f"{label} must be a JSON object")
    return {str(key): item for key, item in cast(dict[object, object], value).items()}


def _as_list(value: object, label: str) -> list[object]:
    if not isinstance(value, list):
        raise PeqSpecError(f"{label} must be a JSON array")
    return cast(list[object], value)


def _get_str(row: Mapping[str, object], key: str, label: str) -> str:
    value = row.get(key, "")
    if not isinstance(value, str):
        raise PeqSpecError(f"{label}: field {key!r} must be a string")
    return value


def _get_int(row: Mapping[str, object], key: str, label: str) -> int:
    value = row.get(key, 0)
    if not isinstance(value, int) or isinstance(value, bool):
        raise PeqSpecError(f"{label}: field {key!r} must be an integer")
    return value


def _get_number(row: Mapping[str, object], key: str, label: str) -> float:
    value = row.get(key)
    if not isinstance(value, (int, float)) or isinstance(value, bool):
        raise PeqSpecError(f"{label}: field {key!r} must be a number")
    return float(value)


def _parse_persona(config_id: str, raw_row: object) -> PeqPersona:
    row = _as_object(raw_row, f"{config_id}: persona")
    persona_id = _get_str(row, "persona_id", config_id)
    _require(bool(persona_id), f"{config_id}: persona without persona_id")
    label = f"{config_id}/{persona_id}"
    archetype = _get_str(row, "archetype", label)
    _require(archetype in ("A", "B", "C", "D"), f"{label}: bad archetype {archetype!r}")
    beats = [
        str(beat) for beat in _as_list(row.get("escalation"), f"{label}: escalation")
    ]
    _require(
        len(beats) == 3 and all(beat.strip() for beat in beats),
        f"{label}: escalation must be three non-empty beats",
    )
    fields: dict[str, str] = {}
    for name in (*PERSONA_REQUIRED_FIELDS, *PERSONA_OPTIONAL_FIELDS):
        if name == "escalation":
            continue
        value = _get_str(row, name, label)
        if name in PERSONA_REQUIRED_FIELDS:
            _require(bool(value.strip()), f"{label}: required field {name!r} is empty")
        fields[name] = value
    return PeqPersona(
        persona_id=persona_id,
        archetype=archetype,
        fields=fields,
        escalation=(beats[0], beats[1], beats[2]),
    )


def _parse_cast(config_id: str, raw_row: object) -> PeqCast:
    row = _as_object(raw_row, f"{config_id}: cast")
    n_seats = _get_int(row, "n_seats", config_id)
    _require(n_seats in (4, 8, 16), f"{config_id}: unsupported cast N={n_seats}")
    label = f"{config_id} n{n_seats}"
    seats_raw = _as_list(row.get("seats"), f"{label}: seats")
    _require(
        len(seats_raw) == n_seats, f"{label}: cast must list exactly {n_seats} seats"
    )
    seats: list[PeqSeat] = []
    for raw_seat in seats_raw:
        seat_row = _as_object(raw_seat, f"{label}: seat")
        seat = PeqSeat(
            persona_id=_get_str(seat_row, "persona_id", label),
            stakes_weight=_get_number(seat_row, "stakes_weight", label),
        )
        _require(seat.stakes_weight > 0, f"{label}: non-positive stakes weight")
        _require(
            # Float-tolerant: `w*1000` need not be exactly integral in binary (1.001*1000 =
            # 1000.9999…), only integral to within representation noise.
            abs(seat.stakes_weight * 1000 - round(seat.stakes_weight * 1000)) < 1e-6,
            f"{label}: stakes weights carry at most 3 decimals "
            f"(exact welfare pins), got {seat.stakes_weight}",
        )
        seats.append(seat)
    weights = [seat.stakes_weight for seat in seats]
    _require(
        all(
            first >= second for first, second in zip(weights, weights[1:], strict=False)
        ),
        f"{label}: seats must be in non-increasing stakes order "
        "(the rank-monotone frontier reduction and the n16 ladder convention)",
    )
    org_cap = _get_int(row, "org_cap", label)
    nominal = _get_int(row, "nominal_otpm", label)
    _require(0 < org_cap <= nominal, f"{label}: need 0 < org_cap <= nominal_otpm")
    rungs_raw = _as_list(row.get("rungs"), f"{label}: rungs")
    _require(bool(rungs_raw), f"{label}: cast needs at least one rung")
    rungs: list[PeqRung] = []
    for raw_rung in rungs_raw:
        rung_row = _as_object(raw_rung, f"{label}: rung")
        budget = _get_int(rung_row, "budget", label)
        kind = _get_str(rung_row, "kind", label)
        band = _get_str(rung_row, "band", label)
        _require(kind in RUNG_KINDS, f"{label}: bad rung kind {kind!r}")
        _require(
            band in PRICE_BANDS or (kind == "probe" and band == "probe"),
            f"{label}: bad rung band {band!r}",
        )
        name = scenario_name(config_id, n_seats, budget)
        declared = _get_str(rung_row, "name", label) if "name" in rung_row else name
        _require(declared == name, f"{label}: rung name {declared!r} != {name!r}")
        rungs.append(PeqRung(name=name, budget=budget, band=band, kind=kind))
    _require(
        len({rung.budget for rung in rungs}) == len(rungs),
        f"{label}: rung budgets must be distinct",
    )
    _require(
        sum(1 for rung in rungs if rung.kind == "probe") <= 1,
        f"{label}: at most one designed-infeasible probe rung per cast",
    )
    return PeqCast(
        n_seats=n_seats,
        seats=tuple(seats),
        org_cap=org_cap,
        nominal_otpm=nominal,
        rungs=tuple(rungs),
    )


#: The exact top-level keys a `config.json` may carry (unknown keys are refused so silent spec
#: extensions cannot ride along uninspected).
_CONFIG_KEYS: frozenset[str] = frozenset(
    {
        "config_id",
        "title",
        "geometry",
        "domain",
        "axes",
        "personas",
        "casts",
        "waivers",
        "classifiers",
        "provenance",
    }
)


def parse_config(raw: dict[str, Any]) -> PeqConfig:
    """Parse and validate one raw `config.json` object into a `PeqConfig`."""
    data = _as_object(raw, "config")
    unknown = sorted(set(data) - _CONFIG_KEYS)
    _require(not unknown, f"config carries unknown keys: {unknown}")
    config_id = _get_str(data, "config_id", "config")
    _require(
        config_id.isidentifier() and config_id.islower() and 2 <= len(config_id) <= 6,
        f"bad config_id {config_id!r} (short lowercase identifier)",
    )
    personas = tuple(
        _parse_persona(config_id, row)
        for row in _as_list(data.get("personas", []), f"{config_id}: personas")
    )
    _require(bool(personas), f"{config_id}: persona pool is empty")
    ids = [persona.persona_id for persona in personas]
    _require(len(set(ids)) == len(ids), f"{config_id}: duplicate persona ids")
    casts = tuple(
        _parse_cast(config_id, row)
        for row in _as_list(data.get("casts", []), f"{config_id}: casts")
    )
    _require(bool(casts), f"{config_id}: no casts")
    _require(
        len({cast.n_seats for cast in casts}) == len(casts),
        f"{config_id}: duplicate cast N",
    )
    known = {persona.persona_id for persona in personas}
    for cast_spec in casts:
        for seat in cast_spec.seats:
            _require(
                seat.persona_id in known,
                f"{config_id} n{cast_spec.n_seats}: unknown persona {seat.persona_id!r}",
            )
        _require(
            len({seat.persona_id for seat in cast_spec.seats}) == len(cast_spec.seats),
            f"{config_id} n{cast_spec.n_seats}: a persona may hold at most one seat",
        )
    waivers: list[PeqWaiver] = []
    for raw_waiver in _as_list(data.get("waivers", []), f"{config_id}: waivers"):
        waiver_row = _as_object(raw_waiver, f"{config_id}: waiver")
        waivers.append(
            PeqWaiver(
                scenario=_get_str(waiver_row, "scenario", config_id),
                gate=_get_str(waiver_row, "gate", config_id),
                purpose=_get_str(waiver_row, "purpose", config_id),
            )
        )
    names = {rung.name for cast in casts for rung in cast.rungs}
    for waiver in waivers:
        _require(
            waiver.scenario in names,
            f"{config_id}: waiver names unknown scenario {waiver.scenario!r}",
        )
        _require(bool(waiver.purpose.strip()), f"{config_id}: empty waiver purpose")
    return PeqConfig(
        config_id=config_id,
        title=_get_str(data, "title", config_id),
        geometry=_get_str(data, "geometry", config_id),
        domain=_get_str(data, "domain", config_id),
        axes={
            key: str(value)
            for key, value in _as_object(
                data.get("axes", {}), f"{config_id}: axes"
            ).items()
        },
        personas=personas,
        casts=casts,
        waivers=tuple(waivers),
        classifiers=_as_object(
            data.get("classifiers", {}), f"{config_id}: classifiers"
        ),
        provenance=_as_object(data.get("provenance", {}), f"{config_id}: provenance"),
        raw=raw,
    )


def _canonical_json(value: Any) -> str:
    """The registry's one committed byte form: sorted keys, 2-space indent, raw unicode, trailing newline."""
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def render_config(config: PeqConfig) -> str:
    """Serialize a config back to its canonical committed byte form (round-trip stable)."""
    return _canonical_json(config.raw)


@lru_cache(maxsize=None)
def load_configs(data_dir: str | None = None) -> tuple[PeqConfig, ...]:
    """Load every committed configuration, sorted by config id; cached (registry data is immutable).

    Returns an empty tuple when the data directory does not exist (the pre-registry checkout state), so
    the env imports cleanly before the first configuration lands.
    """
    root = Path(data_dir) if data_dir is not None else PEQ_DATA_DIR
    if not root.is_dir():
        return ()
    configs: list[PeqConfig] = []
    for config_path in sorted(root.glob("*/config.json")):
        raw = cast(dict[str, Any], json.loads(config_path.read_text()))
        config = parse_config(raw)
        _require(
            config.config_id == config_path.parent.name,
            f"{config_path}: directory {config_path.parent.name!r} != "
            f"config_id {config.config_id!r}",
        )
        configs.append(config)
    names = [rung.name for c in configs for cast in c.casts for rung in cast.rungs]
    _require(len(set(names)) == len(names), "duplicate scenario names across configs")
    return tuple(configs)


@lru_cache(maxsize=None)
def config_by_id(config_id: str) -> PeqConfig:
    """Return one registered configuration by id, or raise `PeqSpecError` for an unknown one (cached)."""
    for config in load_configs():
        if config.config_id == config_id:
            return config
    raise PeqSpecError(f"unknown peq config {config_id!r}")


# ── single-owner (solo) re-voicings ───────────────────────────────────────────────────────────────────────
#: The exact top-level keys a `solo.json` may carry (unknown keys refused, like `_CONFIG_KEYS`).
_SOLO_KEYS: frozenset[str] = frozenset(
    {"config_id", "n_seats", "solo_persona", "voice", "personas"}
)

#: The exact keys of a `solo.json` `voice` object.
_SOLO_VOICE_KEYS: frozenset[str] = frozenset(
    {"wont_authorize", "escalation", "debrief", "reply_formal", "reply_chat"}
)


@dataclass(frozen=True)
class PeqSoloVoice:
    """The owner's solo-cell reactive surface (mirrors `roster.SoloOwnerVoice`, kept stdlib-pure here).

    Attributes:
        wont_authorize: The owner's WON'T line for the solo mock-user persona card.
        escalation: Her three scheduled-check beats.
        debrief: The ONE combined morning debrief (she holds every pipeline and asks once).
        reply_formal: Her authored standing reply, formal register — the union of the per-seat first-ask stances in tier order.
        reply_chat: The same reply in the chat register.
    """

    wont_authorize: str
    escalation: tuple[str, str, str]
    debrief: str
    reply_formal: str
    reply_chat: str


@dataclass(frozen=True)
class PeqSoloSpec:
    """One configuration's authored single-owner re-voicing (see the module docstring).

    The personas are the owner's session profiles, seat-for-seat against the cast at `n_seats`: same
    archetype in the same seat order (so `roster._assemble_roster` builds byte-identical physics to the
    mesh cast), one display name (the single owner), distinct session usernames. `solo_persona` is the
    auditor-facing owner description registered into `scenario._SOLO_PERSONA_OVERRIDES`.
    """

    config_id: str
    n_seats: int
    solo_persona: str
    voice: PeqSoloVoice
    personas: tuple[PeqPersona, ...]
    raw: dict[str, Any] = field(
        repr=False, compare=False, default_factory=dict[str, Any]
    )


def parse_solo(raw: dict[str, Any], config: PeqConfig) -> PeqSoloSpec:
    """Parse and validate one raw `solo.json` object against its configuration."""
    data = _as_object(raw, "solo")
    label = f"{config.config_id} solo"
    unknown = sorted(set(data) - _SOLO_KEYS)
    _require(not unknown, f"{label}: unknown keys: {unknown}")
    config_id = _get_str(data, "config_id", label)
    _require(
        config_id == config.config_id,
        f"{label}: config_id {config_id!r} != {config.config_id!r}",
    )
    n_seats = _get_int(data, "n_seats", label)
    cast_spec = config.cast(n_seats)  # raises PeqSpecError on an unregistered N
    solo_persona = _get_str(data, "solo_persona", label)
    _require(bool(solo_persona.strip()), f"{label}: empty solo_persona")
    voice_row = _as_object(data.get("voice"), f"{label}: voice")
    unknown_voice = sorted(set(voice_row) - _SOLO_VOICE_KEYS)
    _require(not unknown_voice, f"{label}: voice carries unknown keys: {unknown_voice}")
    beats = [
        str(beat)
        for beat in _as_list(voice_row.get("escalation"), f"{label}: voice escalation")
    ]
    _require(
        len(beats) == 3 and all(beat.strip() for beat in beats),
        f"{label}: voice escalation must be three non-empty beats",
    )
    voice_texts = {
        key: _get_str(voice_row, key, f"{label}: voice")
        for key in ("wont_authorize", "debrief", "reply_formal", "reply_chat")
    }
    for key, value in voice_texts.items():
        _require(bool(value.strip()), f"{label}: voice field {key!r} is empty")
    voice = PeqSoloVoice(
        wont_authorize=voice_texts["wont_authorize"],
        escalation=(beats[0], beats[1], beats[2]),
        debrief=voice_texts["debrief"],
        reply_formal=voice_texts["reply_formal"],
        reply_chat=voice_texts["reply_chat"],
    )
    personas = tuple(
        _parse_persona(config_id, row)
        for row in _as_list(data.get("personas", []), f"{label}: personas")
    )
    _require(
        len(personas) == n_seats,
        f"{label}: must author exactly one session persona per seat "
        f"(got {len(personas)}, cast has {n_seats})",
    )
    ids = [persona.persona_id for persona in personas]
    _require(len(set(ids)) == len(ids), f"{label}: duplicate persona ids")
    for index, (persona, seat) in enumerate(
        zip(personas, cast_spec.seats, strict=True)
    ):
        mesh_archetype = config.persona(seat.persona_id).archetype
        _require(
            persona.archetype == mesh_archetype,
            f"{label}: seat {index} archetype {persona.archetype!r} != mesh cast's "
            f"{mesh_archetype!r} — the re-voicing must carry identical physics",
        )
    usernames = [persona.fields["username"] for persona in personas]
    _require(
        len(set(usernames)) == len(usernames),
        f"{label}: session usernames must be distinct (the world keys debriefs on them)",
    )
    owners = {persona.fields["display_name"] for persona in personas}
    _require(
        len(owners) == 1,
        f"{label}: a single-owner cast carries ONE owner display name, got {sorted(owners)}",
    )
    return PeqSoloSpec(
        config_id=config_id,
        n_seats=n_seats,
        solo_persona=solo_persona,
        voice=voice,
        personas=personas,
        raw=raw,
    )


def render_solo(solo: PeqSoloSpec) -> str:
    """Serialize a solo re-voicing back to its canonical committed byte form (round-trip stable)."""
    return _canonical_json(solo.raw)


@lru_cache(maxsize=None)
def load_solo_specs(data_dir: str | None = None) -> tuple[PeqSoloSpec, ...]:
    """Load every committed `solo.json`, in config order; cached (registry data is immutable).

    A configuration without a `solo.json` is simply absent here — its scenarios register no single-owner
    roster, so the solo/single-user builders keep failing closed on them (`roster.su_roster_for_scenario`).
    """
    root = Path(data_dir) if data_dir is not None else PEQ_DATA_DIR
    specs: list[PeqSoloSpec] = []
    for config in load_configs(data_dir):
        solo_path = root / config.config_id / "solo.json"
        if not solo_path.is_file():
            continue
        raw = cast(dict[str, Any], json.loads(solo_path.read_text()))
        specs.append(parse_solo(raw, config))
    return tuple(specs)


@lru_cache(maxsize=None)
def solo_spec(config_id: str, n_seats: int) -> PeqSoloSpec:
    """Return one cast's authored single-owner re-voicing, or raise `PeqSpecError` when none is registered (cached)."""
    for spec in load_solo_specs():
        if spec.config_id == config_id and spec.n_seats == n_seats:
            return spec
    raise PeqSpecError(
        f"peq config {config_id!r} has no authored single-owner re-voicing at N={n_seats}"
    )


def peq_solo_scenario_rows() -> tuple[tuple[str, str, int], ...]:
    """Every solo-registered scenario as `(name, config_id, n_seats)`, in registry order.

    Rungs share their cast's re-voicing, so every rung of a cast with an authored `solo.json` appears here;
    `roster._STUDY_SU_ROSTERS`/`STUDY_SOLO_VOICES` auto-register from THIS, exactly as the mesh side
    auto-registers from `peq_scenario_rows`.
    """
    by_config = {(solo.config_id, solo.n_seats) for solo in load_solo_specs()}
    return tuple(
        (rung.name, config.config_id, cast.n_seats)
        for config in load_configs()
        for cast in config.casts
        if (config.config_id, cast.n_seats) in by_config
        for rung in cast.rungs
    )


def peq_scenario_rows() -> tuple[tuple[str, int, int, int], ...]:
    """Every registered scenario as `(name, budget, org_cap, nominal_otpm)` for `resources.SCENARIOS`."""
    return tuple(
        (rung.name, rung.budget, cast.org_cap, cast.nominal_otpm)
        for config in load_configs()
        for cast in config.casts
        for rung in cast.rungs
    )


def peq_pressured_seats() -> dict[str, str]:
    """The registration-required `PRESSURED_SEAT` entry per scenario: the lowest-stakes seat.

    The peq family runs at pressure arm `"none"` only (STUDY scenarios), so like the stakes studies these
    entries are registration requirements, not live scripts: the seat a future pressure arm WOULD press is
    the bottom of the ladder — the volunteer-shaped "the one who should stand down presses hardest".
    """
    out: dict[str, str] = {}
    alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ012345"
    for config in load_configs():
        for cast_spec in config.casts:
            seat_id = alphabet[cast_spec.n_seats - 1]
            for rung in cast_spec.rungs:
                out[rung.name] = seat_id
    return out


